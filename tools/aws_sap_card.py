"""Generate the AWS/SAP per-screen story from one source of truth.

Three outputs, all from tools/aws_sap_map.py:

    web/*.html                    the strip each screen carries (between markers)
    demo/aws-sap-per-screen.md    the written map
    demo/aws-sap-per-screen.pdf   one page a judge can photograph

Idempotent: running it twice leaves the same bytes. The strip lives between
`<!-- PROV:BEGIN -->` and `<!-- PROV:END -->`, so a hand edit inside those markers is
replaced on the next run and an edit outside them survives.

Run
---
    .venv/bin/python tools/aws_sap_card.py
"""

from __future__ import annotations

import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))

import aws_sap_map as M                                              # noqa: E402

WEB = ROOT / "web"
DEMO = ROOT / "demo"
MARK_BEGIN = "<!-- PROV:BEGIN -->"
MARK_END = "<!-- PROV:END -->"

CSS = """
/* ── provenance strip: which AWS and SAP parts make this screen true ── */
.prov { margin: var(--space-2xl, 3rem) 0 0; padding-top: var(--space-sm, .6rem);
        border-top: 1px solid var(--color-rule, #d8d5cd);
        color: var(--color-muted, #6b6a64);
        font: 400 var(--text-sm, .8rem) / 1.7 var(--font-body, sans-serif); }
.prov-k { display: inline-block; margin-right: .35rem; padding: .05rem .4rem;
          border: 1px solid currentColor; border-radius: 2px;
          font: 500 var(--text-xs, .68rem) / 1.5 var(--font-ui, monospace);
          letter-spacing: .08em; text-transform: uppercase; }
.prov-sep { margin: 0 .5rem; opacity: .55; }
.prov code { font-family: var(--font-ui, monospace); font-size: .95em; }
"""


def strip_block(entry: dict) -> str:
    return f"{MARK_BEGIN}\n{M.strip(entry)}\n{MARK_END}\n"


def inject_strips() -> list[str]:
    """Put each screen's strip in its page, replacing whatever is between the markers."""
    touched = []
    for entry in M.MAP:
        page = WEB / entry["file"]
        if not page.exists():
            raise SystemExit(f"page missing: {page}")
        html = page.read_text()
        block = strip_block(entry)
        if MARK_BEGIN in html and MARK_END in html:
            html = re.sub(
                re.escape(MARK_BEGIN) + r".*?" + re.escape(MARK_END) + r"\n?",
                block, html, flags=re.S)
        elif "</body>" in html:
            html = html.replace("</body>", block + "</body>", 1)
        else:
            raise SystemExit(f"no </body> in {page}")
        page.write_text(html)
        touched.append(entry["file"])
    return touched


def ensure_css() -> bool:
    css = WEB / "pasok.css"
    text = css.read_text()
    if ".prov {" in text:
        return False
    css.write_text(text.rstrip() + "\n" + CSS)
    return True


def write_md() -> pathlib.Path:
    out = DEMO / "aws-sap-per-screen.md"
    lines = [
        "# The AWS and SAP parts, per screen",
        "",
        "Generated by `tools/aws_sap_card.py` from `tools/aws_sap_map.py`. The same file puts",
        "the one-line strip at the foot of every console page, so what a judge reads here is",
        "what the screen in front of them says. `tools/ui_component_gate.py` fails if the two",
        "ever disagree.",
        "",
        "Rubric line this answers: **technical execution on AWS/SAP, 25 percent**. The answer",
        "is components, screen by screen, and an honest list of what the account gate blocks.",
        "",
    ]
    for entry in M.MAP:
        lines += [
            f"## `{entry['route']}` — {entry['name']}",
            "",
            f"**What the screen claims.** {entry['claim']}",
            "",
            f"**AWS.** {entry['aws']}",
            "",
            f"**SAP.** {entry['sap']}",
            "",
            f"**Honest limit.** {entry['gated']}",
            "",
        ]
    lines += [
        "## What the account gate blocks, and what runs instead",
        "",
        "| Gate | Evidence | What runs today |",
        "|---|---|---|",
    ]
    for gate, evidence, instead in M.GATES:
        lines.append(f"| {gate} | {evidence} | {instead} |")
    lines += [
        "",
        "Reproduce: `aws/GATES.md`, from account `<account-id>`, region `us-west-2`.",
        "",
        "## Not claimed",
        "",
        M.NOT_CLAIMED,
        "",
        "## Proof the AWS lane is live right now",
        "",
        "```bash",
        f"curl -s -X POST {M.LAMBDA_URL} -H 'Content-Type: application/json' \\",
        "  -d '{\"action\":\"network\"}' | head -c 120",
        "# -> {\"learn_summary\": …, \"decision_summary\": …, \"order_summary\": …}",
        "```",
        "",
        "Public HTTPS, no credentials. The same handler answers `exceptions`, `sku` and `ask`.",
        "",
        "## SAP, live",
        "",
        f"- orchestration deployment `{M.ORCH_DEPLOYMENT}`, model `{M.MODEL}`: the console's",
        "  answer lane (`/api/ask`), the run report, and one rationale per escalated order",
        "  (`data/sap/rationales.csv`, 40 of 40)",
        "- `sap-rpt-1.6` tabular scoring over the whole catalog in one call:",
        "  `data/sap/rpt_scores.csv`, 600 rows, `STOCKOUT_NEXT14`, `EXPIRY_RISK`,",
        "  `DAYS_COVER_LEFT` with confidences",
        "- Joule capability published to the tenant for the approval moment",
        "  (`joule/pasok_a2a/`, `joule lint` clean)",
        "",
    ]
    out.write_text("\n".join(lines) + "\n")
    return out


