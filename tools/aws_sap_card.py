def write_card() -> tuple[pathlib.Path, pathlib.Path]:
    rows = []
    for e in M.MAP:
        rows.append(
            "<tr>"
            f'<td class="r">{e["route"]}<br><span style="font-weight:400">{e["name"]}</span></td>'
            f"<td>{M.rich(e['aws'])}</td><td>{M.rich(e['sap'])}</td>"
            f"<td>{M.rich(e['gated'])}</td>"
            "</tr>")
    gates = " ".join(f"{g} — {ev} → {ins}." for g, ev, ins in M.GATES)
    html = HTML.format(rows="\n".join(rows), gates=gates, url=M.LAMBDA_URL,
                       orch=M.ORCH_DEPLOYMENT, model=M.MODEL, notclaimed=M.NOT_CLAIMED)
    src = DEMO / "aws-sap-per-screen.html"
    src.write_text(html)
    pdf = DEMO / "aws-sap-per-screen.pdf"
    if pdf.exists():
        pdf.unlink()
    subprocess.run(
        ["google-chrome", "--headless", "--disable-gpu", "--no-sandbox",
         "--no-pdf-header-footer", f"--print-to-pdf={pdf}", str(src)],
        capture_output=True, text=True, timeout=180,
    )
    return src, pdf


def main() -> int:
    touched = inject_strips()
    print("strips refreshed:", ", ".join(touched))
    print("css added:", ensure_css())
    md = write_md()
    src, pdf = write_card()
    print("written:", md.name, "|", src.name, "|", pdf.name,
          f"({pdf.stat().st_size // 1024} KB)" if pdf.exists() else "(pdf missing)")
    pages = subprocess.run(["pdfinfo", str(pdf)], capture_output=True, text=True).stdout
    for line in pages.splitlines():
        if line.startswith(("Pages", "Page size")):
            print("card", line)
    return 0


if __name__ == "__main__":
    sys.exit(main())
